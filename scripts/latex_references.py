"""Export cross-document labels as TeX inputs that survive source uploads."""
from pathlib import Path


def groups(text):
    """Read balanced top-level TeX groups, preserving nested groups verbatim."""
    result, start, depth = [], None, 0
    for i, char in enumerate(text):
        escaped = (len(text[:i]) - len(text[:i].rstrip('\\'))) % 2
        if escaped:
            continue
        if char == '{':
            if depth == 0:
                start = i + 1
            depth += 1
        elif char == '}':
            depth -= 1
            if depth < 0:
                raise ValueError('Unbalanced label group')
            if depth == 0:
                result.append(text[start:i])
    if depth:
        raise ValueError('Unclosed label group')
    return result


def export_references(directory, exports):
    """Return whether any generated reference input changed."""
    directory = Path(directory)
    changed = False
    for item in exports:
        source = directory / item['source']
        if not source.exists():
            continue
        labels = []
        for line in source.read_text(encoding='utf-8').splitlines():
            if not line.startswith('\\newlabel{'):
                continue
            key, value = groups(line)
            fields = groups(value)
            fields = (fields + ['', '', '', ''])[:4]
            fields.append(item['url'])
            labels.append('\\newlabel{' + key + '}{' +
                          ''.join('{' + field + '}' for field in fields) + '}')
        output = '% Generated by the PDF build. Do not edit label values.\n' + '\n'.join(labels) + '\n'
        target = directory / item['output']
        if not target.exists() or target.read_text(encoding='utf-8') != output:
            target.write_text(output, encoding='utf-8', newline='\n')
            changed = True
    return changed

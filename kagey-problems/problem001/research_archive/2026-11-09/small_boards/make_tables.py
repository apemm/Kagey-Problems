"""Write structure_tables.md from verify_all.json, structure.json and cross_board.json."""
import json
from boards import HERE

ver = {r['name']: r for r in json.loads((HERE / 'verify_all.json').read_text())}
st = json.loads((HERE / 'structure.json').read_text())
cb = json.loads((HERE / 'cross_board.json').read_text())
B = st['boards']
L = []


def table(head, rows):
    L.append('| ' + ' | '.join(head) + ' |')
    L.append('|' + '|'.join('---' for _ in head) + '|')
    for r in rows:
        L.append('| ' + ' | '.join(str(x) for x in r) + ' |')
    L.append('')


L.append('# Structure tables for the stored equality boards')
L.append('')
L.append('Generated by `make_tables.py` from `verify_all.json`, `structure.json` and `cross_board.json`. '
         'The reading of these tables is in `structure_summary.md`.')
L.append('')
L.append('Board names: `h7_w21_a` to `d` are the four 7 x 21 boards; `h11_w169` is `cegar_h11_warm_t3`; '
         '`h15_w441_oddsea` and `h15_w441_binary` are the two coordinate files at height 15; '
         '`h19_w713_binary` is the height 19 coordinate file. The other rows are controls: the 9 x 77 board, '
         'three more 11 x 169 boards, and the three repeated-gap boards at height 15.')
L.append('')
L.append('## 0. Independent verification')
L.append('')
table(['board', 'h', 'm', 'black', 'doubles', 'rectangles', 'with two or more black corners', 'hidden',
       'distinct presentations', 'valid'],
      [[n, r['height'], r['width'], r['black'], r['doubles'], r['rectangles'],
        r['rectangles_with_two_or_more_black_corners'], r['hidden_rectangles'],
        r['distinct_presentations_among_them'], r['valid']] for n, r in ver.items()])
L.append(f"The four 7 x 21 boards form one orbit under the two reflections: {st['seven_row_boards_form_one_reflection_orbit']}.")
L.append('')

L.append('## a. Labels')
L.append('')
table(['board', 'partition', 'first to last label column', 'gaps between labels (gap: count)',
       'moduli with one residue class'],
      [[r['name'], r['row_partition'], f"{r['core'][0]} to {r['core'][1]}",
        ', '.join(f'{k}: {v}' for k, v in r['gap_histogram'].items()),
        r['single_residue_moduli'] or 'none'] for r in B])
L.append('Fits of the label order. Slot = rank of the label from the left. i, j = rank of the odd row and of the '
         'even row inside their classes. "Shuffled" = the same statistic for random orders.')
L.append('')
rows = []
for r in B:
    lf = r['linear_fit']; md = r['modular_fit_slot_eq_alpha_i_plus_beta_j_plus_gamma']
    exact = [N for N, x in md.items() if x['slot_best_fraction'] == 1.0]
    over = [N for N, x in md.items() if x['slot_best_fraction'] > x['shuffled_max']]
    sh = r['consecutive_labels_sharing_a_row']
    rows.append([r['name'], lf['slot']['R2'], f"{lf['slot_R2_shuffled_mean_max'][0]} / {lf['slot_R2_shuffled_mean_max'][1]}",
                 exact or 'none', over or 'none', f'{sh[0]} / {sh[1]}'])
table(['board', 'R2 of slot = alpha a + beta b + gamma', 'shuffled R2 mean / max',
       'moduli N <= 12 with an exact rule slot = alpha i + beta j + gamma mod N',
       'moduli where the best fit beats all 40 shuffles', 'consecutive labels sharing a row: actual / shuffled'], rows)
L.append('Slot residue explained by row residues (fraction of labels on the majority value; actual / shuffled mean).')
L.append('')
keys = list(B[0]['slot_class_explained_by_row_residues'].keys())
table(['board'] + keys, [[r['name']] + [f'{v[0]} / {v[1]}' for v in r['slot_class_explained_by_row_residues'].values()] for r in B])
L.append('Label orders, left to right (odd row-even row):')
L.append('')
for r in B:
    L.append(f"- `{r['name']}`: " + ' '.join(f'{a}-{b}' for a, b in r['label_order']))
L.append('')

L.append('## b. Fillers')
L.append('')
L.append('The core is the stretch from the first to the last label column.')
L.append('')
table(['board', 'core fillers by row (row: count)', 'row 1', 'row h', 'interior rows', 'even rows',
       'distinct gap words', 'most frequent gap words (word x count)', 'best period of the core word (match, period)'],
      [[r['name'], ', '.join(f'{k}: {v}' for k, v in r['filler_histogram_core'].items()),
        r['core_filler_fraction_row_1'], r['core_filler_fraction_row_h'], r['core_filler_fraction_interior'],
        r['core_filler_fraction_even_rows'], r['distinct_gap_words'],
        '; '.join(f'({w or "empty"}) x {c}' for w, c in r['gap_words'][:3]),
        f"{r['core_word_best_periods_fraction_period'][0][0]}, {r['core_word_best_periods_fraction_period'][0][1]}"]
       for r in B])

L.append('## c. Three-black tilted right angles')
L.append('')
L.append('A triangle is a tilted rectangle with exactly three black corners. Its white corner is the completion cell.')
L.append('')
rows = []
for r in B:
    t = r['triangles_by_labelcells_completioncolumn_class']
    inlab = sum(x[3] for x in t if x[1] == 'label column')
    opp = sum(x[3] for x in t if x[2] != 'same class')
    n = r['triangles_by_number_of_label_cells']
    pl = r['triangles_per_label_mean_max_min']
    rows.append([r['name'], r['triangles_total'], r['triangles_per_column'], n['0'], n['1'], n['2'], n['3'],
                 inlab, opp, pl[0], pl[1], r['shuffled_order_fatal_triangles_mean_min'][0],
                 r['shuffled_order_fatal_triangles_per_label']])
table(['board', 'triangles', 'per column', '0 label cells', '1', '2', '3', 'completion in a label column',
       'completion row class differs from the filler', 'per label mean', 'per label max',
       'fatal triangles, shuffled order (mean)', 'same, per label'], rows)
L.append('Distance between the completion row and the filler row of the completion column (distance: count):')
L.append('')
for r in B:
    L.append(f"- `{r['name']}`: " + ', '.join(f'{k}: {v}' for k, v in r['triangle_completion_row_distance_to_filler'].items()))
L.append('')

L.append('## d. Tilted shapes with two or more black corners')
L.append('')
rows = []
for r in B:
    tw = {(a, b, c): v for a, b, c, v in r['two_black_rectangles_by_type']}
    ff_side = tw.get(('filler-filler', 'side', 'full height'), 0) + tw.get(('filler-filler', 'side', 'shorter'), 0)
    rows.append([r['name'], r['tilted_shape_classes_fitting'], r['shape_classes_never_two_black'],
                 r['shape_classes_with_three_black'], r['tilted_placements'], r['fraction_with_two_or_more_black'],
                 r['random_filler_rows_fraction_with_two_or_more_black'], ff_side,
                 tw.get(('filler-filler', 'diagonal', 'shorter'), 0), tw.get(('filler-filler', 'diagonal', 'full height'), 0)])
table(['board', 'shape classes that fit', 'classes never showing two black corners', 'classes showing three',
       'tilted placements', 'fraction with two or more black', 'same with random filler rows',
       'filler-filler pairs as a side', 'filler-filler diagonal, shorter shape', 'filler-filler diagonal, full height'], rows)
L.append('Exactly-two-black tilted rectangles by pair type (pair, position, shape height: count):')
L.append('')
for r in B:
    L.append(f"- `{r['name']}`: " + '; '.join(f'{a}, {b}, {c}: {v}' for a, b, c, v in r['two_black_rectangles_by_type']))
L.append('')

L.append('## e. Vertical rivals')
L.append('')
L.append('A pair of black cells in opposite row classes at offset (dx, dy) with dx^2 + dy^2 = L^2 is the black diagonal '
         'of a tilted rectangle whose white diagonal is vertical, of length L, through the same midpoint. If that '
         'vertical diagonal fits in the grid, the double column owning its two rows gives an axis rival. '
         'L is odd, so dx is divisible by 4.')
L.append('')
table(['board', 'violations', 'Pythagorean opposite-class pairs present (kind, triple, status: count)',
       'opposite-class pairs within h columns', 'of these with dx divisible by 4',
       'vertical-rival pairs, shuffled order (mean, min)', 'fraction of shuffles with none'],
      [[r['name'], r['vertical_rival_violations'],
        '; '.join(f'{a} {b} {c}: {v}' for a, b, c, v in r['pythagorean_opposite_class_pairs']) or 'none',
        r['opposite_class_pairs_within_h_columns'], r['of_which_column_difference_divisible_by_4'],
        f"{r['shuffled_order_vertical_rival_pairs_mean_min'][0]}, {r['shuffled_order_vertical_rival_pairs_mean_min'][1]}",
        r['shuffled_order_fraction_without_vertical_rival']] for r in B])
L.append('Filler columns by offset from the nearest label column mod 4 and by row class (offset, class: count):')
L.append('')
for r in B:
    L.append(f"- `{r['name']}`: " + '; '.join(f'{a}, {b}: {v}' for a, b, v in r['filler_column_offset_mod4_from_nearest_label_by_row_class']))
L.append('')

L.append('## Cross-height tests of the order')
L.append('')
table(['lower board', 'upper board', 'row shift', 'common pairs', 'Spearman rank correlation of slots', '95% point of the null'],
      [[x['lower'], x['upper'], x['row_shift'], x['common_pairs'], x['spearman'], x['null_abs_95_percentile']]
       for x in cb['rank_correlation']])
L.append('Restriction of the 19-row order to a 15-row window, placed at columns 8j+1 with the gap 1,1,1,15,1,1,1:')
L.append('')
table(['rows of the 19-row board', 'labels', 'valid', 'clashing presentations', 'fatal triangles', 'vertical-rival pairs'],
      [[f"{x['rows_of_19_used'][0]} to {x['rows_of_19_used'][1]}", x['labels'], x['valid'], x['clashing_presentations'],
        x['fatal_triangles'], x['vertical_rival_pairs']] for x in cb['restriction']])
(HERE / 'structure_tables.md').write_text('\n'.join(L) + '\n', encoding='utf-8')
print('written', len(L), 'lines')

"""Orbits of the three-row optima under the Klein four-group.

The group is generated by the reflection of the rows (row 1 <-> row 3) and the reversal
of the columns; the product is the half turn of the 3 x m grid.  Burnside's lemma gives

    o_3(m) = (a_3(m) + r_m + v_m + w_m) / 4,

with r_m, v_m, w_m the numbers of optima fixed by the reflection, the reversal and the
half turn.  Column words use the letters a, b, c (single black row 1, 2, 3), A = rows 1,2,
B = rows 1,3, C = rows 2,3, X = all three rows; an optimum has one X or two distinct
doubles, every other column a singleton.

Three routes are compared:
  (1) formulas: r_m = [m = 3]; v_m = 0 for even m and v_{2k+1} = the number of words w of
      length k over {a,b,c} with no window b?b, last letter b and (k >= 2) second-to-last
      letter outer; w_m = 2 w^{AC}_m + [m odd] x_m with w^{AC}_m = 2 floor(m/2) 3^(floor(m/2)-2)
      for m >= 4 (1 at m = 3) and x_{2k+1} = number of words of length k with no window
      b?b whose second-to-last letter (k >= 2) is outer;  rational generating functions and
      closed forms are derived with sympy from the four-state transfer matrix of the b?b
      rule;
  (2) table: the symmetric words are enumerated directly (they are determined by half of
      the word) and tested against the forbidden three-letter windows of the three classes;
  (3) definition: every optimum is generated for 3 <= m <= 7 by testing all (m+2)-subsets
      of the grid with verify_narrow.collision, and for 8 <= m <= 10 by testing every
      candidate word (one X or two distinct doubles) with verify_narrow.collision; the
      group acts on the words and the orbits are counted directly.

Coordinates in the output are one-based (column, row), (1,1) top left, as in
verify_narrow (bit (row-1)*m + (column-1)); internally rows and columns are zero based.
Output: jis/data/three_row_orbits.json.
"""
import json
import os
import sys
import time
from itertools import combinations, product
from pathlib import Path

import sympy as sp

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
DATA = os.path.join(os.path.dirname(HERE), 'data')
sys.path.insert(0, ROOT)
import verify_narrow  # noqa: E402

REFERENCE = Path(__file__).resolve().parent.parent / 'data' / 'three_row_reference'
COUNTS = REFERENCE / 'three_row_classes.json'
WINDOWS = REFERENCE / 'three_row_windows.json'

LETTERS = {'a': (0,), 'b': (1,), 'c': (2,), 'A': (0, 1), 'B': (0, 2), 'C': (1, 2), 'X': (0, 1, 2)}
ROWSET = {v: k for k, v in LETTERS.items()}
SWAP = str.maketrans('acAC', 'caCA')
TIME_LIMIT = 1700


def reflect(w):
    return w.translate(SWAP)


def reverse(w):
    return w[::-1]


def half_turn(w):
    return reflect(reverse(w))


def word_to_mask(w):
    m = len(w)
    return sum(1 << (r * m + x) for x, ch in enumerate(w) for r in LETTERS[ch])


def mask_to_word(mask, m):
    cols = []
    for x in range(m):
        rows = tuple(r for r in range(3) if mask >> (r * m + x) & 1)
        if rows not in ROWSET:
            return None
        cols.append(ROWSET[rows])
    return ''.join(cols)


def word_to_points(w):
    """One-based (column, row) list."""
    return [[x + 1, r + 1] for x, ch in enumerate(w) for r in LETTERS[ch]]


def candidate_words(m):
    singles = 'abc'
    for i in range(m):
        for rest in product(singles, repeat=m - 1):
            yield ''.join(rest[:i]) + 'X' + ''.join(rest[i:])
    for i, j in combinations(range(m), 2):
        for d1, d2 in product('ABC', repeat=2):
            if d1 == d2:
                continue
            for rest in product(singles, repeat=m - 2):
                w = list(rest[:i]) + [d1] + list(rest[i:j - 1]) + [d2] + list(rest[j - 1:])
                yield ''.join(w)


def optima_by_definition(m, rects):
    cells = 3 * m
    found = []
    for S in combinations(range(cells), m + 2):
        mask = sum(1 << i for i in S)
        if verify_narrow.collision(rects, mask) is None:
            found.append(mask)
    return found


def optima_by_candidates(m, rects):
    return [w for w in candidate_words(m) if verify_narrow.collision(rects, word_to_mask(w)) is None]


def orbit_data(words):
    S = set(words)
    fixed = {'reflection': sum(1 for w in S if reflect(w) == w),
             'reversal': sum(1 for w in S if reverse(w) == w),
             'half_turn': sum(1 for w in S if half_turn(w) == w)}
    orbits = set()
    sizes = {}
    for w in S:
        imgs = {w, reflect(w), reverse(w), half_turn(w)}
        assert imgs <= S, 'the optimum set is not closed under the group'
        rep = min(imgs)
        orbits.add(rep)
        sizes[rep] = len(imgs)
    size_hist = {}
    for s in sizes.values():
        size_hist[s] = size_hist.get(s, 0) + 1
    return fixed, len(orbits), size_hist, sorted(orbits)


# ---------------------------------------------------------------- route (2): table
def load_windows():
    with open(WINDOWS) as fh:
        d = json.load(fh)['local']
    return {k: set(d[k]['bad']) for k in ('AC', 'AB', 'X')}


def word_class(w):
    ex = [ch for ch in w if ch in 'ABCX']
    if ex == ['X']:
        return 'X'
    s = frozenset(ex)
    if s == frozenset('AC'):
        return 'AC'
    return 'AB'


def normalise_to_table(w):
    """Map a word to the ordered class AC, AB or X used by the window tables."""
    ex = [ch for ch in w if ch in 'ABCX']
    if ex == ['X']:
        return w, 'X'
    s = frozenset(ex)
    if s == frozenset('AC'):
        return (w if ex == ['A', 'C'] else reverse(w)), 'AC'
    # outer pair classes AB, BA, BC, CB -> AB by reversal and/or reflection
    if s == frozenset('BC'):
        w = reflect(w)
        ex = [ch for ch in w if ch in 'ABCX']
    if ex == ['B', 'A']:
        w = reverse(w)
    return w, 'AB'


def table_valid(w, bad):
    v, cls = normalise_to_table(w)
    return all(v[i:i + 3] not in bad[cls] for i in range(len(v) - 2))


def symmetric_words(m, kind):
    """All candidate words fixed by the given group element."""
    out = set()
    if kind == 'reflection':
        # letters fixed by a<->c, A<->C: b, B, X; two doubles would both be B: excluded
        for i in range(m):
            out.add('b' * i + 'X' + 'b' * (m - 1 - i))
        return out
    f = reverse if kind == 'reversal' else half_turn
    k = m // 2
    if m % 2 == 1:
        for half in product('abc', repeat=k):
            left = ''.join(half)
            out.add(left + 'X' + f(left))
    # two doubles at mirrored positions i, m-1-i (and a single X cannot be fixed at even m)
    for i in range(k):
        for d in 'ABC':
            e = f(d)
            if e == d:
                continue
            for half in product('abc', repeat=k - 1):
                left = list(half)
                left.insert(i, d)
                left = ''.join(left)
                mid = ''
                if m % 2 == 1:
                    for c in 'abc':
                        if f(c) == c:
                            out.add(left + c + f(left))
                else:
                    out.add(left + f(left))
    return out


def fixed_counts_by_table(m, bad):
    res = {}
    for kind in ('reflection', 'reversal', 'half_turn'):
        words = symmetric_words(m, kind)
        fmap = {'reflection': reflect, 'reversal': reverse, 'half_turn': half_turn}[kind]
        assert all(fmap(w) == w for w in words)
        res[kind] = sorted(w for w in words if table_valid(w, bad))
    return res


# ---------------------------------------------------------------- route (1): formulas
def formulas(max_m):
    """Exact fixed counts from the b?b transfer matrix, plus generating functions."""
    z = sp.symbols('z')
    # states: bits of the last two letters (b = 1); transition (i,j)->(j,k) forbidden if i=k=1
    K = sp.Matrix([[2, 1, 0, 0], [0, 0, 2, 1], [2, 0, 0, 0], [0, 0, 2, 0]])
    # words of length k >= 2 by last-two state: start vector after two letters
    # (no restriction between the first two letters): counts 4, 2, 2, 1 for 00, 01, 10, 11
    start = sp.Matrix([[4, 2, 2, 1]])
    H = (sp.eye(4) - z * K).inv()
    gen = start * H           # entry s: sum_{k>=2} N_k(s) z^(k-2)
    N_01 = sp.cancel(gen[1])
    N_0x = sp.cancel(gen[0] + gen[1])
    # v(z) = sum_m v_m z^m = z^3 + sum_{k>=2} N_k(01) z^(2k+1)
    V = sp.cancel(z ** 3 + z ** 5 * N_01.subs(z, z ** 2))
    # x(z) = sum over odd m of x_m z^m = 3 z^3 + sum_{k>=2} (N_k(00)+N_k(01)) z^(2k+1)
    Xg = sp.cancel(3 * z ** 3 + z ** 5 * N_0x.subs(z, z ** 2))
    # AC part: 2 w^AC_m = 2 at m = 3, 4 n 3^(n-2) for m = 2n, 2n+1 >= 4
    # sum_{n>=2} 4 n 3^(n-2) t^n with t = z^2, times (1 + z): (4/9) (1+z) (T/(1-T)^2 - T), T = 3 z^2
    T = 3 * z ** 2
    WAC = sp.cancel(2 * z ** 3 + sp.Rational(4, 9) * (1 + z) * (T / (1 - T) ** 2 - T))
    W = sp.cancel(WAC + Xg)
    series = {}
    for name, g in (('v', V), ('w', W), ('x', Xg), ('wAC', WAC)):
        s = sp.Poly(sp.series(g, z, 0, max_m + 1).removeO(), z)
        series[name] = [int(s.coeff_monomial(z ** k)) for k in range(max_m + 1)]
    # closed forms for N_k(01) and N_k(00)+N_k(01) with simple poles rho, sigma, +-i sqrt2
    k = sp.symbols('k', integer=True)
    s3, is2 = sp.sqrt(3), sp.I * sp.sqrt(2)
    closed = {}
    for name, g, seq in (('v', N_01, None), ('x', N_0x, None)):
        coeffs = sp.Poly(sp.series(g, z, 0, 20).removeO(), z)
        vals = [int(coeffs.coeff_monomial(z ** j)) for j in range(20)]   # N_{j+2}
        al, be, ga, de = sp.symbols('al be ga de')
        expr = al * (1 + s3) ** k + be * (1 - s3) ** k + ga * is2 ** k + de * (-is2) ** k
        sol = sp.solve([sp.Eq(expr.subs(k, j + 2), vals[j]) for j in range(4)], [al, be, ga, de])
        cf = expr.subs(sol)
        ok = all(sp.nsimplify(sp.expand(cf.subs(k, j + 2))) == vals[j] for j in range(20))
        assert ok
        closed[name] = {'N_k_closed_form': str(sp.simplify(cf)), 'checked_k_2_to_21': ok,
                        'coefficients': {str(a): str(sol[a]) for a in (al, be, ga, de)}}
    # product forms: f_n = no-consecutive-b words of length n over {a,b,c} (f_0=1, f_1=3, f_n=2f_{n-1}+2f_{n-2});
    # v_{2k+1} = 4 f_{ceil(k/2)-2} f_{floor(k/2)-1} (k>=3), x_{2k+1} = 2 f_{ceil(k/2)} f_{floor(k/2)-1} (k>=2)
    f = [1, 3]
    for _ in range(max_m):
        f.append(2 * f[-1] + 2 * f[-2])
    prod_ok = True
    for kk in range(2, max_m // 2):
        mm = 2 * kk + 1
        xv = 2 * f[(kk + 1) // 2] * f[kk // 2 - 1]
        vv = 4 * f[(kk + 1) // 2 - 2] * f[kk // 2 - 1] if kk >= 3 else 2
        prod_ok = prod_ok and series['x'][mm] == xv and series['v'][mm] == vv
    series['product_forms_agree'] = prod_ok
    assert prod_ok
    gfs = {'v': str(sp.factor(V)), 'x_odd_part_of_w': str(sp.factor(Xg)), 'wAC_times_2': str(sp.factor(WAC)),
           'w': str(sp.factor(W))}
    return series, gfs, closed


def main():
    t0 = time.time()
    out = {'date': '2026-10-17', 'python': sys.version.split()[0], 'sympy': sp.__version__,
           'coordinates': 'one-based (column,row), (1,1) top left', 'group': 'Klein four-group: row reflection, column reversal, half turn'}
    with open(COUNTS) as fh:
        a3 = json.load(fh)['counts']['total']
    MAXF = 100
    series, gfs, closed = formulas(MAXF)
    r = [1 if m == 3 else 0 for m in range(MAXF + 1)]
    v, w = series['v'], series['w']
    o = {}
    for m in range(3, MAXF + 1):
        tot = a3[m] + r[m] + v[m] + w[m]
        assert tot % 4 == 0, (m, tot)
        o[m] = tot // 4
    out['burnside'] = {'o3_3_to_15': {m: o[m] for m in range(3, 16)},
                       'o3_integral_3_to_100': True,
                       'r_reflection_fixed_3_to_15': r[3:16], 'v_reversal_fixed_3_to_15': v[3:16],
                       'w_half_turn_fixed_3_to_15': w[3:16], 'x_odd_X_part_of_w_3_to_15': series['x'][3:16],
                       'wAC_times_2_3_to_15': series['wAC'][3:16],
                       'generating_functions': gfs, 'closed_forms_of_N_k': closed,
                       'o3_3_to_40': [o[m] for m in range(3, 41)]}
    print('o_3(3..15) =', [o[m] for m in range(3, 16)])
    print('v =', v[3:16]); print('w =', w[3:16])

    bad = load_windows()
    table = {}
    for m in range(3, 25):
        fc = fixed_counts_by_table(m, bad)
        table[m] = {k: len(val) for k, val in fc.items()}
        if m <= 6:
            table[m]['words'] = fc
    agree = all(table[m]['reflection'] == r[m] and table[m]['reversal'] == v[m] and table[m]['half_turn'] == w[m]
                for m in range(3, 25))
    out['table_route'] = {'fixed_counts_3_to_24': table, 'agrees_with_formulas': agree}
    assert agree
    print('table route agrees with formulas through m=24:', agree)

    brute = {}
    for m in range(3, 11):
        if time.time() - t0 > TIME_LIMIT:
            brute[m] = 'unresolved: time limit'
            continue
        t1 = time.time()
        rects = verify_narrow.rectangles(3, m)
        if m <= 7:
            masks = optima_by_definition(m, rects)
            words = [mask_to_word(mk, m) for mk in masks]
            assert None not in words, 'an optimum outside the candidate family'
            cand = set(optima_by_candidates(m, rects))
            assert cand == set(words)
            route = 'all (m+2)-subsets; candidate family agrees'
        else:
            words = optima_by_candidates(m, rects)
            route = 'candidate family (one X or two distinct doubles), each tested against every rectangle'
        fixed, n_orb, hist, reps = orbit_data(words)
        entry = {'route': route, 'rectangles': len(rects), 'a3': len(words), 'fixed': fixed, 'orbits': n_orb,
                 'orbit_size_histogram': hist, 'seconds': round(time.time() - t1, 1),
                 'burnside_agrees': (fixed['reflection'] == r[m] and fixed['reversal'] == v[m]
                                     and fixed['half_turn'] == w[m] and n_orb == o[m] and len(words) == a3[m])}
        fixed_words = {k: sorted(ww for ww in set(words) if f(ww) == ww)
                       for k, f in (('reflection', reflect), ('reversal', reverse), ('half_turn', half_turn))}
        entry['fixed_words'] = fixed_words
        if m <= 5:
            entry['fixed_points_one_based'] = {k: [word_to_points(ww) for ww in val] for k, val in fixed_words.items()}
            entry['orbit_representatives'] = reps
        brute[m] = entry
        print('m=%d: a3=%d fixed=%s orbits=%d burnside=%s %.1fs' % (m, len(words), fixed, n_orb, entry['burnside_agrees'], time.time() - t1), flush=True)
    out['definition_route'] = brute
    out['seconds'] = round(time.time() - t0, 1)
    os.makedirs(DATA, exist_ok=True)
    with open(os.path.join(DATA, 'three_row_orbits.json'), 'w') as fh:
        json.dump(out, fh, indent=1)
    print('done in', out['seconds'], 's')


if __name__ == '__main__':
    main()
